/**
 * Invitations saved before the envelope gained flap, texture and seal have no
 * such keys. Fill any gap from the design while keeping every saved value.
 */
export function resolveEnvelope(envelope: Envelope, designSlug?: string): Envelope {
  const merged: Envelope = { ...defaultEnvelope(getDesign(designSlug ?? 'gilded-arch')) };
  for (const [key, value] of Object.entries(envelope)) {
    if (value !== undefined && value !== null) {
      (merged as unknown as Record<string, unknown>)[key] = value;
    }
  }
  return merged;
}

